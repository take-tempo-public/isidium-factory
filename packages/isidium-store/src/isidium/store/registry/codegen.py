# ---- write / verify --------------------------------------------------------------------------------------------


def generate(registry: Registry | None = None, out: Path | None = None) -> dict[Path, str]:
    """Render every generated artifact; returns {path: text} without writing (the drift test compares). The tool
    schemas ride the generated model, so `models.py` must already be on disk — it is, checked in; a models drift is
    reported first."""
    reg = registry or Registry.shipped()
    root = out or GENERATED
    return {root / "models.py": render_models(reg), root / "tools.json": render_tools(reg)}


def write(registry: Registry | None = None, out: Path | None = None) -> list[Path]:
    """Two phases: the model first, then the tool schemas that ride it (the bootstrap of a fresh checkout)."""
    import importlib

    reg = registry or Registry.shipped()
    root = out or GENERATED
    root.mkdir(parents=True, exist_ok=True)
    models_path = root / "models.py"
    models_path.write_bytes(render_models(reg).encode("utf-8"))
    importlib.invalidate_caches()
    from .generated import models as models_mod

    importlib.reload(models_mod)
    tools_path = root / "tools.json"
    tools_path.write_bytes(render_tools(reg).encode("utf-8"))
    return [models_path, tools_path]


def drift(registry: Registry | None = None) -> list[Path]:
    """The paths whose checked-in bytes differ from what the schemas render — empty, or the build is out of date."""
    return [p for p, text in generate(registry).items() if not p.is_file() or p.read_bytes() != text.encode("utf-8")]


