# Names that would shadow a pydantic BaseModel attribute; pinned here, aliased like a keyword.
RESERVED: Final[frozenset[str]] = frozenset({"schema", "json", "dict", "copy", "fields", "construct", "validate"})
SCALARS: Final[dict[str, str]] = {
    "string": "str",
    "int": "int",
    "bool": "bool",
    "date": "str",
    "array": "list[Any]",
    "table": "dict[str, Any]",
}


def _py_type(row: Mapping[str, Any], overrides: Mapping[str, str]) -> str:
    name = str(row["name"])
    if name in overrides:
        return overrides[name]
    if "enum" in row:
        members = ", ".join(json.dumps(m) for m in row["enum"])
        return f"Literal[{members}]"
    return SCALARS.get(str(row.get("type")), "Any")


def _required(row: Mapping[str, Any]) -> bool:
    """Unconditionally required = `required_when = []` (an AND of no tests, L2-5). Conditionally required keys are
    Optional in the model and enforced by the profile — the tool surface must be able to compose a draft."""
    return row.get("required_when") == []


def _field_lines(rows: Sequence[Mapping[str, Any]], overrides: Mapping[str, str]) -> list[str]:
    """One line per key row. A key that is a Python keyword (`for`, `from`) or a pydantic attribute (`schema`) is
    emitted with a trailing underscore and its wire name as the alias; `model_dump(exclude_unset=True,
    by_alias=True)` is the one dump, so the raw value tree carries the schema's own key."""
    out: list[str] = []
    for row in rows:
        name = str(row["name"])
        t = _py_type(row, overrides)
        py = name + "_" if keyword.iskeyword(name) or name in RESERVED else name
        alias = f', alias="{name}"' if py != name else ""
        if _required(row):
            out.append(f"    {py}: {t}" + (f" = Field({alias[2:]})" if alias else ""))
        elif alias:
            out.append(f"    {py}: {t} | None = Field(default=None{alias})")
        else:
            out.append(f"    {py}: {t} | None = None")
    return out


def _model(class_name: str, doc: SchemaDoc, part: str, overrides: Mapping[str, str], doc_line: str) -> list[str]:
    rows = list(doc.get(part, []))
    lines = [f"class {class_name}(Strict):", f'    """{doc_line}"""', ""]
    lines += _field_lines(rows, overrides) or ["    pass"]
    lines.append("")
    lines.append("")
    return lines


def render_models(registry: Registry) -> str:
    card = registry.get("card@1")
    inbox = registry.get("inbox@1")
    sources = ", ".join(f"{d['name']}@{d['version']}" for d in (card, inbox))
    address = canon.content_address([card, inbox])
    body: list[str] = []
    body += _model(
        "CardHead",
        card,
        "head",
        CARD_FIELD_TYPES,
        "A card's typed head (03 §2.1). Conditionally required keys are Optional here; the profile (03 §3) decides.",
    )
    body += _model(
        "InboxRecord",
        inbox,
        "record",
        {"refs": "list[str]", "surfaces_touched": "list[str]", "from": "dict[str, Any]"},
        "One suggestion-inbox record (03a §2): intake or disposition; per-type presence is the record slot's.",
    )
    return HEADER.format(sources=sources, address=address) + "\n\n" + "\n".join(body).rstrip() + "\n"


