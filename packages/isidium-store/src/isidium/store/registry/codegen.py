"""One schema, three consumers (03b §4): the validator inside `write` (registry/config.py, registry/card.py), the
**typed model** and the **tool-call input schema** — both generated here from the same registry documents, so
"nothing to drift" is a test, not a hope (`tests/unit/test_codegen.py` regenerates and byte-compares).

What is generated: for each document type, a pydantic model whose scalar/table rows come from the schema document's
key rows (name, type, enum, pattern, range, required_when, default) and whose nested shapes are the discriminated
models of `registry/shapes.py` — the declared limit of the nine-member vocabulary, authored once and shared by the
three targets. From the model: the JSON Schema each tool call is constrained to, which is what makes "no freehand"
cheap rather than bureaucratic (round 57).

`model_dump(exclude_unset=True, by_alias=True)` is the one dump: the typed model is validated, never hashed, so
absent-vs-default survives into the raw value tree the hasher sees (W10, T6).
"""

